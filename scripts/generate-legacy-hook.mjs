import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "src-tauri", "nsis", "cleanup-legacy-engine.ps1");
const hookPath = path.join(root, "src-tauri", "nsis", "hooks.nsi");
const source = await readFile(sourcePath, "utf8");
const existingHook = await readFile(hookPath, "utf8");
const postInstallMarker = "!macro NSIS_HOOK_POSTINSTALL";
const postInstallIndex = existingHook.indexOf(postInstallMarker);

if (postInstallIndex < 0) {
  throw new Error("POSTINSTALL marker was not found in hooks.nsi");
}

const encoded = Buffer.from(source, "utf16le").toString("base64");
const chunks = encoded.match(/.{1,700}/g) ?? [];
const bootstrapScript =
  `$b=[string]::Concat((1..${chunks.length}|ForEach-Object{` +
  `[Environment]::GetEnvironmentVariable(('MAVRODPI_LEGACY_SCRIPT_'+$_),'Process')}));` +
  `&([ScriptBlock]::Create([Text.Encoding]::Unicode.GetString(` +
  `[Convert]::FromBase64String($b))))`;
const bootstrap = Buffer.from(bootstrapScript, "utf16le").toString("base64");

if (chunks.some((chunk) => chunk.length > 700) || bootstrap.length >= 1024) {
  throw new Error("Generated NSIS strings exceed the safe string limit");
}

const defines = chunks
  .map((chunk, index) => `!define MAVRODPI_LEGACY_SCRIPT_${index + 1} "${chunk}"`)
  .join("\n");
const setChunks = chunks
  .map(
    (_, index) => `    System::Call 'kernel32::SetEnvironmentVariableW(w "MAVRODPI_LEGACY_SCRIPT_${index + 1}", w "\${MAVRODPI_LEGACY_SCRIPT_${index + 1}}") i.r9'
    \${If} $R9 = 0
      StrCpy $R7 "Güncelleme temizleme adımı hazırlanamadı (${index + 1})."
      Goto mavrodpi_legacy_cleanup_env
    \${EndIf}`,
  )
  .join("\n");
const clearChunks = chunks
  .map(
    (_, index) =>
      `    System::Call 'kernel32::SetEnvironmentVariableW(w "MAVRODPI_LEGACY_SCRIPT_${index + 1}", p 0)'`,
  )
  .join("\n");

const generated = `; Generated by scripts/generate-legacy-hook.mjs from cleanup-legacy-engine.ps1.
; The UTF-16LE payload is split because bundled NSIS uses a 1024-character string limit.
${defines}
!define MAVRODPI_LEGACY_BOOTSTRAP "${bootstrap}"

!macro NSIS_HOOK_PREINSTALL
  ; v0.2.4 did not own its foreground engine with a Job Object. During an
  ; updater install, terminate only the executable in this exact install path.
  \${If} $UpdateMode = 1
    StrCpy $R7 ""
    System::Call 'kernel32::SetEnvironmentVariableW(w "MAVRODPI_LEGACY_ENGINE_PATH", w "$INSTDIR\\resources\\goodbyedpi\\x86_64\\goodbyedpi.exe") i.r9'
    \${If} $R9 = 0
      StrCpy $R7 "Eski koruma motoru yolu hazırlanamadı."
      Goto mavrodpi_legacy_cleanup_env
    \${EndIf}
    System::Call 'kernel32::SetEnvironmentVariableW(w "MAVRODPI_CIM_MODULE", w "$SYSDIR\\WindowsPowerShell\\v1.0\\Modules\\CimCmdlets\\CimCmdlets.psd1") i.r9'
    \${If} $R9 = 0
      StrCpy $R7 "Güvenilir Windows CIM bileşeni hazırlanamadı."
      Goto mavrodpi_legacy_cleanup_env
    \${EndIf}

${setChunks}

    DetailPrint "Önceki MavroDPI koruma motoru exact-path ile denetleniyor..."
    nsExec::ExecToLog '"$SYSDIR\\WindowsPowerShell\\v1.0\\powershell.exe" -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand \${MAVRODPI_LEGACY_BOOTSTRAP}'
    Pop $R8
    \${If} $R8 != 0
      StrCpy $R7 "Önceki koruma motoru güvenli biçimde kapatılamadı (kod: $R8)."
    \${EndIf}

    mavrodpi_legacy_cleanup_env:
    System::Call 'kernel32::SetEnvironmentVariableW(w "MAVRODPI_LEGACY_ENGINE_PATH", p 0)'
    System::Call 'kernel32::SetEnvironmentVariableW(w "MAVRODPI_CIM_MODULE", p 0)'
${clearChunks}

    \${If} $R7 != ""
      DetailPrint "$R7"
      SetErrorLevel 1
      IfSilent mavrodpi_legacy_cleanup_abort 0
      MessageBox MB_ICONSTOP|MB_OK "$R7$\\r$\\nGüncelleme dosyaları değiştirilmeden durduruldu."
      mavrodpi_legacy_cleanup_abort:
      Abort
    \${EndIf}
  \${EndIf}
!macroend

`;

await writeFile(hookPath, generated + existingHook.slice(postInstallIndex), "utf8");
console.log(`Generated ${chunks.length} payload chunks; bootstrap=${bootstrap.length} chars.`);
